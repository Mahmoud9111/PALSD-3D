const BODY_ROUGHNESS = 0.45;

// Deterministic 0..1 hash from a face centroid — keeps the jitter stable across
// renders (no flicker) while still looking randomly hand-painted.
function faceHash(x: number, y: number, z: number) {
  const s = Math.sin(x * 12.9898 + y * 78.233 + z * 37.719) * 43758.5453;
  return s - Math.floor(s);
}

// Paint the single truck mesh: split every triangle into its own vertices (so
// colours stay crisp at the seams and normals come out flat-faceted), then tint
// each face by height into tracks / chassis / body.
function buildTruckGeometry(source: THREE.BufferGeometry) {
  const geo = source.toNonIndexed();
  geo.computeVertexNormals(); // non-indexed → per-face flat normals (low-poly look)

  const pos = geo.getAttribute("position") as THREE.BufferAttribute;
  const nor = geo.getAttribute("normal") as THREE.BufferAttribute;
  geo.computeBoundingBox();
  const bb = geo.boundingBox!;
  const minY = bb.min.y;
  const spanY = bb.max.y - bb.min.y || 1;
  const halfZ = Math.max(Math.abs(bb.min.z), Math.abs(bb.max.z)) || 1;

  const body = new THREE.Color(BODY_COLOR);
  const chassis = new THREE.Color(CHASSIS_COLOR);
  const track = new THREE.Color(TRACK_COLOR);
  const cab = new THREE.Color(CAB_COLOR);
  const exhaust = new THREE.Color(EXHAUST_COLOR);
  const tmp = new THREE.Color();

  const colors = new Float32Array(pos.count * 3);
  const faceCount = pos.count / 3;

  for (let f = 0; f < faceCount; f++) {
    const a = f * 3;
    // face centroid
    const cx = (pos.getX(a) + pos.getX(a + 1) + pos.getX(a + 2)) / 3;
    const cy = (pos.getY(a) + pos.getY(a + 1) + pos.getY(a + 2)) / 3;
    const cz = (pos.getZ(a) + pos.getZ(a + 1) + pos.getZ(a + 2)) / 3;

    const h = (cy - minY) / spanY; // 0 at the bottom, 1 at the top
    const sideways = Math.abs(cz) / halfZ; // 0 at the centreline, 1 at the edges
    const ny = nor.getY(a); // face normal Y (flat-shaded → one normal per face)

    let isBody = false;
    if (h < TRACK_TOP) {
      // low + out toward the sides = crawler track; low + central = dark chassis
      tmp.copy(sideways > 0.45 ? track : chassis);
    } else if (h < CHASSIS_TOP) {
      tmp.copy(chassis);
    } else if (h < CAB_BOTTOM) {
      // amber hopper & side body panels
      tmp.copy(body);
      isBody = true;
    } else if (h < EXHAUST_BOTTOM) {
      // operator cab cluster on top — seats & control screens (black)
      tmp.copy(cab);
    } else {
      // thin posts at the very top — exhaust pipe & beacon stack (grey)
      tmp.copy(exhaust);
    }

    // ── Bake the premium depth shading into the face colour ──────────────────
    // 1) a soft vertical gradient (sky-lit top, shaded base),
    // 2) a contact-shade on downward-facing faces (fake AO in the crevices),
    // 3) body only: a faint sky-catch sheen on up-facing panels + the
    //    hand-painted per-face jitter so the amber isn't dead-flat.
    let light = (h - 0.5) * AO_GRADIENT;
    if (ny < 0) light -= AO_UNDERSIDE * -ny;
    if (isBody) {
      if (ny > 0) light += TOP_SHEEN * ny;
      light += (faceHash(cx, cy, cz) - 0.5) * 2 * BODY_JITTER;
    }
    tmp.offsetHSL(0, 0, light);

    for (let v = 0; v < 3; v++) {
      const i = (a + v) * 3;
      colors[i] = tmp.r;
      colors[i + 1] = tmp.g;
      colors[i + 2] = tmp.b;
    }
  }

  geo.setAttribute("color", new THREE.BufferAttribute(colors, 3));
  return geo;
}

