const AO_GRADIENT = 0.16; // bottom of the truck is this much darker than the top
const AO_UNDERSIDE = 0.24; // extra darkening on downward-facing faces (contact shade)
const TOP_SHEEN = 0.06; // faint brighten on up-facing body panels (catches the sky)

