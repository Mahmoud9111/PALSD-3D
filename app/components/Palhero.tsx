function buildStreetLines(geometry: THREE.BufferGeometry) {
  geometry.computeBoundingBox();
  const bb = geometry.boundingBox!;
  const [px, py, pz] = STREET_POSITION;
  const [sx, sy, sz] = STREET_SCALE;

  // mesh has no rotation, so world extent = position + scale * local extent
  const minX = px + sx * bb.min.x;
  const maxX = px + sx * bb.max.x;
  const minZ = pz + sz * bb.min.z;
  const maxZ = pz + sz * bb.max.z;

  const lengthX = maxX - minX;
  const widthZ = maxZ - minZ;
  const centerX = (minX + maxX) / 2;
  const centerZ = (minZ + maxZ) / 2;

  // dashed centre line — evenly spaced dash centres along the road
  const dashCount = 390; // more dashes → closer together (scaled with the 3× longer road)
  const span = lengthX * 0.96;
  const step = span / dashCount;
  const dashes: number[] = [];
  for (let i = 0; i < dashCount; i++) {
    dashes.push(centerX - span / 2 + step * (i + 0.5));
  }

  return {
    y: py + sy * bb.max.y + 0.01, // sit flush, just above the road's top face
    centerX,
    centerZ,
    lengthX,
    stripeW: Math.max(widthZ * 0.035, 0.04), // painted-stripe width (in Z)
    edgeZ: widthZ * 0.42, // how far the edge lines sit from centre
    dashLen: step * 0.3, // short dashes
    dashes,
  };
}

