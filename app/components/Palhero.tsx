const GRID_FRAGMENT_SHADER = /* glsl */ `
  #include <fog_pars_fragment>

  uniform float uTime;
  uniform float uSpeed;
  uniform float uSquareSize;
  uniform float uLineWidth;
  uniform float uOpacity;
  uniform float uFillOpacity;
  uniform float uHoverOpacity;
  uniform float uHoverTrail;
  uniform vec2  uPlaneSize;
  uniform vec2  uDir;
  uniform vec2  uHover;
  uniform vec3  uBorderColor;
  uniform vec3  uFillColor;
  uniform vec3  uHoverColor;

  varying vec2 vUv;

  void main() {
    // Grid coordinates measured in whole cells; scroll over time for the
    // diagonal animation (uSpeed = 0 → a static grid, like ShapeGrid speed={0}).
    vec2 cells  = (vUv * uPlaneSize) / uSquareSize + uDir * uTime * uSpeed;
    vec2 cellId = floor(cells);
    vec2 f      = fract(cells);

    // Anti-aliased border: distance (in cell units) to the nearest cell edge.
    vec2 distEdge = min(f, 1.0 - f);
    float d  = min(distEdge.x, distEdge.y);
    float t  = uLineWidth / uSquareSize;   // line half-width as a fraction of a cell
    float aa = fwidth(d);
    float line = 1.0 - smoothstep(t - aa, t + aa, d);

    // Hover fill — a square (Chebyshev) block of cells around the hovered one.
    float hover = 0.0;
    if (uHover.x > -0.5) {
      vec2 hd = abs(cellId - uHover);
      float cheb = max(hd.x, hd.y);
      hover = 1.0 - step(uHoverTrail + 0.5, cheb);
    }

    // Compose: resting square fill → hover fill on the hovered block → grey
    // border lines on top of everything.
    vec3  color = uFillColor;
    float alpha = uFillOpacity;
    color = mix(color, uHoverColor, hover);
    alpha = max(alpha, hover * uHoverOpacity);
    color = mix(color, uBorderColor, line);
    alpha = max(alpha, line * uOpacity);

    if (alpha < 0.001) discard;

    gl_FragColor = vec4(color, alpha);
    #include <fog_fragment>
  }
`;

